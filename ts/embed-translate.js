// Generate the TypeScript translation interface and the packaged Go and Rust
// copies from the repository's one manifest and alchemy sources.

const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..')
const manifestPath = path.join(root, 'tabnas.plugin.json')
const manifestText = fs.readFileSync(manifestPath, 'utf8')
const manifest = JSON.parse(manifestText)
const spec = manifest.translate

if (null == spec) {
  throw new Error('tabnas.plugin.json has no translate object')
}

const languageId = manifest.languageId
if ('string' !== typeof languageId || '' === languageId) {
  throw new Error('tabnas.plugin.json has no languageId')
}

function part (kind) {
  const value = spec[kind]
  if (null == value) return undefined
  if ('string' !== typeof value || '' === value) {
    throw new Error(`translate.${kind} is not a non-empty string`)
  }

  if (!value.endsWith('.alc')) {
    return { entry: value }
  }

  const sourcePath = path.join(root, value)
  const source = fs.readFileSync(sourcePath, 'utf8')
  return { entry: `${languageId}-${kind}`, source, file: path.basename(value) }
}

const lift = part('lift')
const embed = part('embed')
const render = part('render')

function tsPart (value) {
  if (null == value) return undefined
  const fields = [`entry: ${JSON.stringify(value.entry)}`]
  if (null != value.source) fields.push(`source: ${tsString(value.source)}`)
  return `Object.freeze({ ${fields.join(', ')} })`
}

function tsString (value) {
  return '`' + value
    .replaceAll('\\', '\\\\')
    .replaceAll('`', '\\`')
    .replaceAll('${', '\\${') + '`'
}

const fields = [`manifest: ${tsString(manifestText)}`]
if (lift) fields.push(`lift: ${tsPart(lift)}`)
if (embed) fields.push(`embed: ${tsPart(embed)}`)
if (render) fields.push(`render: ${tsPart(render)}`)

const generated = `/* Copyright (c) 2026 Richard Rodger and other contributors, MIT License */

// Generated by ../embed-translate.js. Edit tabnas.plugin.json or alchemy/*,
// then run npm run embed.

type TranslationPart = Readonly<{
  entry: string
  source?: string
}>

type TranslationParts = Readonly<{
  manifest: string
  lift?: TranslationPart
  embed?: TranslationPart
  render?: TranslationPart
}>

const TRANSLATION: TranslationParts = Object.freeze({
  ${fields.join(',\n  ')}
})

function translate (): TranslationParts | undefined {
  return TRANSLATION
}

export {
  translate,
}

export type {
  TranslationPart,
  TranslationParts,
}
`

fs.writeFileSync(path.join(__dirname, 'src', 'translate.ts'), generated)

for (const runtime of ['go', 'rs']) {
  const target = path.join(root, runtime, 'translate')
  fs.mkdirSync(target, { recursive: true })
  fs.writeFileSync(path.join(target, 'manifest.json'), manifestText)
  for (const value of [lift, embed, render]) {
    if (value?.source) fs.writeFileSync(path.join(target, value.file), value.source)
  }
}
